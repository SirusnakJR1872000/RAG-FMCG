"""Measure the time of every pipeline stage and the memory used (PROJECT_SPEC §20, §19.1).

Usage (from backend/):  python -m scripts.measure_latency [--n 10]

Runs the real pipeline (real models, real Ollama): one warm-up question that is not counted,
then `--n` dev questions (START_HERE M5: 10), then a scripted 3-turn conversation so the
follow-up rewrite is measured too. Writes reports/latency.md and reports/latency.json.

Ollama caches the processed prompt of recent requests, so asking the same question again
within the 30-minute keep-alive is much faster than a first-time question. The script unloads
the model first so that every run starts cold.

Honest by construction: the report records how busy the machine was (free RAM, swap) because
latency on a 16 GB laptop with a browser open is not the latency of an idle server.
"""

import argparse
import asyncio
import datetime as dt
import json
import resource
import sys
from pathlib import Path

import numpy as np

from config import get_settings
from scripts.build_index import git_commit
from scripts.run_eval import GOLDEN
from src.evaluation.golden import load_golden
from src.generation.ollama_client import OllamaError
from src.generation.pipeline import RagPipeline, Result
from src.generation.prompts import Exchange

# p50 targets, PROJECT_SPEC §20 (milliseconds)
TARGETS_MS = {"rewrite": 10_000, "retrieval": 300, "rerank": 2_000, "ttft": 30_000,
              "total": 90_000}
STAGE_LABEL = {"rewrite": "Standalone rewrite (follow-ups only)",
               "retrieval": "Embedding + FAISS + BM25 + RRF", "rerank": "Reranking 20 candidates",
               "ttft": "Time to first token (from request)", "total": "Full answer"}
# a scripted conversation: each turn only makes sense with the previous one
CONVERSATION = ["What must happen when an out-of-specification result is obtained?",
                "How many working days does Acme allow for the first laboratory investigation?",
                "And when does a CAPA have to be raised after that?"]
WARMUP = "What does the guidance require for out-of-specification results?"


def summarise(values: list[float]) -> dict[str, float]:
    if not values:
        return {"n": 0, "p50": 0.0, "p90": 0.0}
    return {"n": len(values), "p50": round(float(np.percentile(values, 50))),
            "p90": round(float(np.percentile(values, 90)))}


def meminfo() -> dict[str, int]:
    """System memory in MB from /proc/meminfo (Linux)."""
    wanted = {"MemTotal", "MemAvailable", "SwapTotal", "SwapFree"}
    values = {}
    for line in Path("/proc/meminfo").read_text().splitlines():
        key, _, rest = line.partition(":")
        if key in wanted:
            values[key] = int(rest.split()[0]) // 1024
    values["SwapUsed"] = values["SwapTotal"] - values["SwapFree"]
    return values


def peak_rss_mb() -> int:
    return resource.getrusage(resource.RUSAGE_SELF).ru_maxrss // 1024  # Linux: kilobytes


def stage_values(results: list[tuple[str, Result]], stage: str) -> list[float]:
    """Latencies of one stage; rewrite only counts turns that had one, TTFT only real answers."""
    values = []
    for _, r in results:
        v = r.latency_ms.get(stage, 0)
        if stage == "ttft" and r.answer_type == "retrieval_refusal":
            continue
        if stage in ("rewrite", "ttft") and v == 0:
            continue
        values.append(v)
    return values


def render(report: dict) -> str:
    stages, mem = report["stages"], report["memory"]
    lines = [
        "# Latency and memory", "",
        f"Generated by `python -m scripts.measure_latency` on {report['date']}, git commit "
        f"`{report['git_commit']}`.",
        f"Models: answers and rewrite `{report['llm_model']}` (Ollama, `num_ctx` "
        f"{report['num_ctx']}), embeddings `{report['embedding_model']}`, reranker "
        f"`{report['reranker_model']}`. CPU only, {report['cpus']} logical cores.",
        f"{report['n_single']} dev questions + a {report['n_conversation']}-turn conversation, "
        "after one warm-up question that is not counted. Targets are the p50 targets of "
        "PROJECT_SPEC §20.", "",
        "## State of the machine (read this before the numbers)", "",
        f"- Free RAM before the run: **{report['mem_before']['MemAvailable']} MB** of "
        f"{report['mem_before']['MemTotal']} MB; swap in use: **{report['mem_before']['SwapUsed']}"
        f" MB** of {report['mem_before']['SwapTotal']} MB.",
        "- Other applications were running (this is a development laptop, not an idle server). "
        "If RAM is short, the model's weights are paged in and out and every stage gets slower.",
        "", "## Stage latencies (milliseconds)", "",
        "| Stage | Target p50 | Measured p50 | p90 | n | Result |", "|---|---|---|---|---|---|"]
    for key, label in STAGE_LABEL.items():
        s = stages[key]
        ok = s["n"] > 0 and s["p50"] <= TARGETS_MS[key]
        lines.append(f"| {label} | ≤ {TARGETS_MS[key]:,} | {s['p50']:,} | {s['p90']:,} | {s['n']} "
                     f"| {'✅ met' if ok else '❌ missed'} |")
    llm = report["llm"]
    lines += [
        "", "## Generation", "",
        f"- Output speed: **{llm['tokens_per_second_p50']} tokens/s** (p50); answers had "
        f"{llm['completion_tokens_p50']} tokens at p50.",
        f"- Prompt size: p50 {llm['prompt_tokens_p50']} tokens, **max {llm['prompt_tokens_max']}** "
        f"of the {report['num_ctx']}-token context (§9.2 budgets about 1,900 including output).",
        f"- Answers cut off at the length limit: {llm['truncated']} of {llm['answers']}.",
        f"- Citation check: {llm['citation_ok']} ok, {llm['citation_invalid']} invalid, "
        f"{llm['citation_uncited']} uncited (of {llm['answers']} answers).",
        f"- Refusals: {llm['retrieval_refusals']} retrieval, {llm['model_refusals']} model.",
        "", "## Memory (PROJECT_SPEC §19.1 budget)", "",
        "| Consumer | Budget | Measured |", "|---|---|---|",
        f"| Backend process (Python + PyTorch + embedding model + reranker + FAISS + BM25), "
        f"peak RSS | 1.5–2.5 GB | {mem['backend_peak_rss_mb']:,} MB |",
        f"| Ollama, {report['llm_model']} resident | 5.5–6.5 GB | "
        f"{mem['ollama_resident_mb']:,} MB |",
        f"| Free RAM after the run | — | {report['mem_after']['MemAvailable']:,} MB |",
        f"| Swap in use after the run | — | {report['mem_after']['SwapUsed']:,} MB |", ""]
    missed = [STAGE_LABEL[k] for k in STAGE_LABEL if stages[k]["n"] and
              stages[k]["p50"] > TARGETS_MS[k]]
    if missed:
        lines += ["## Targets missed", "",
                  "Missed: " + "; ".join(missed) + ".", "",
                  "PROJECT_SPEC §20: apply in this order, re-measure and re-evaluate after "
                  "each step, and record what was applied: (1) context 4 → 3 chunks, "
                  "(2) `num_predict` 400 → 300, (3) the faster reranker if within 2 points "
                  "of dev Hit@5, (4) benchmark `llama3.2:3b` as the answer model. "
                  "**None has been applied yet.**", ""]
    lines += ["## Every question", "",
              "| Question | Type | Rewrite | Retrieval | Rerank | First token | Total | Tokens |",
              "|---|---|---|---|---|---|---|---|"]
    for q in report["questions"]:
        lines.append(f"| {q['question'][:70]} | {q['answer_type']} | {q['rewrite']} | "
                     f"{q['retrieval']} | {q['rerank']} | {q['ttft']} | {q['total']} | "
                     f"{q['completion_tokens']} |")
    return "\n".join(lines) + "\n"


async def measure(n: int) -> dict:
    settings = get_settings()
    dev = [g.question for g in load_golden(GOLDEN) if g.split == "dev" and g.answerable][:n]
    pipeline = RagPipeline(settings)
    await pipeline.client.unload()  # a cold start: no cached prompts from earlier questions
    await pipeline.warm_up()
    print("warm-up question …", flush=True)
    await pipeline.answer(WARMUP)
    mem_before = meminfo()

    runs: list[tuple[str, Result]] = []
    for i, question in enumerate(dev, start=1):
        result = await pipeline.answer(question)
        runs.append((question, result))
        print(f"  {i}/{len(dev)} {result.latency_ms['total'] / 1000:5.1f} s  "
              f"{result.answer_type}  {question[:60]}", flush=True)
    history: list[Exchange] = []
    for i, question in enumerate(CONVERSATION, start=1):
        result = await pipeline.answer(question, history)
        history.append(Exchange(question, result.answer))
        runs.append((question, result))
        print(f"  turn {i} {result.latency_ms['total'] / 1000:5.1f} s  rewrite "
              f"{result.latency_ms['rewrite']} ms  {result.answer_type}", flush=True)

    ollama = await pipeline.client.loaded_models()
    await pipeline.aclose()
    answered = [r for _, r in runs if r.answer_type != "retrieval_refusal"]
    llm_runs = [r for r in answered if r.llm]
    tps = [r.llm["tokens_per_second"] for r in llm_runs if r.llm["tokens_per_second"]]
    prompt = [r.llm["prompt_tokens"] for r in llm_runs]
    done = [r.llm["completion_tokens"] for r in llm_runs]
    checks = [r.citation_check.status for r in answered if r.citation_check]
    return {
        "date": dt.date.today().isoformat(), "git_commit": git_commit(),
        "llm_model": settings.llm_model, "num_ctx": settings.llm_num_ctx,
        "embedding_model": settings.embedding_model, "reranker_model": settings.reranker_model,
        "cpus": __import__("os").cpu_count(), "n_single": len(dev),
        "n_conversation": len(CONVERSATION),
        "stages": {k: summarise(stage_values(runs, k)) for k in STAGE_LABEL},
        "llm": {
            "tokens_per_second_p50": round(float(np.median(tps)), 2) if tps else 0,
            "completion_tokens_p50": round(float(np.median(done))) if done else 0,
            "prompt_tokens_p50": round(float(np.median(prompt))) if prompt else 0,
            "prompt_tokens_max": max(prompt, default=0), "answers": len(llm_runs),
            "truncated": sum(r.truncated for r in llm_runs),
            "citation_ok": checks.count("ok"), "citation_invalid": checks.count("invalid_citation"),
            "citation_uncited": checks.count("uncited_answer"),
            "retrieval_refusals": sum(r.answer_type == "retrieval_refusal" for _, r in runs),
            "model_refusals": sum(r.answer_type == "model_refusal" for _, r in runs)},
        "memory": {"backend_peak_rss_mb": peak_rss_mb(),
                   "ollama_resident_mb": round(sum(m.get("size", 0) for m in ollama) / 2**20)},
        "mem_before": mem_before, "mem_after": meminfo(),
        "questions": [{"question": q, "answer_type": r.answer_type,
                       "completion_tokens": r.llm.get("completion_tokens", 0), **{
                           k: r.latency_ms.get(k, 0)
                           for k in ("rewrite", "retrieval", "rerank", "ttft", "total")}}
                      for q, r in runs],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--n", type=int, default=10, help="dev questions to run (default 10)")
    args = parser.parse_args()
    try:
        report = asyncio.run(measure(args.n))
    except OllamaError as exc:
        print(f"[{exc.code}] {exc}")
        return 1
    reports = get_settings().reports_dir
    (reports / "latency.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (reports / "latency.md").write_text(render(report), encoding="utf-8")
    print(f"\nwrote {reports / 'latency.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
