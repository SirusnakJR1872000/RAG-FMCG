"""Choose the relevance threshold τ on the dev split (PROJECT_SPEC §8.5, D-15).

Usage (from backend/):  python -m scripts.tune_threshold

τ is applied to the RERANKER score of the best candidate: below it, the answer is "not
covered" and the LLM is never called. (Not the RRF score: RRF only depends on rank positions,
so a perfectly irrelevant question would score as high as a perfect one.)

Rule (§8.5): the τ that maximises refusal accuracy on the unanswerable dev questions while
rejecting at most 1 in 20 answerable ones. Several τ values usually tie; the middle of that
range is chosen so the margin to both groups is as large as possible. Only the dev split is
used — the test split is never looked at while tuning (§11.1).
"""

import datetime as dt
import sys
from dataclasses import dataclass

from config import get_settings
from scripts.build_index import git_commit
from scripts.run_eval import GOLDEN
from src.evaluation.golden import load_golden
from src.generation.pipeline import RagPipeline

MAX_FALSE_REFUSAL = 0.05  # §8.5: answerable recall ≥ 0.95


@dataclass(frozen=True)
class ThresholdChoice:
    tau: float
    refusal_accuracy: float  # share of unanswerable questions refused
    false_refusal_rate: float  # share of answerable questions refused
    margin_below: float  # tau minus the highest refused score (room on the refusal side)
    margin_above: float  # lowest answerable score minus tau (room on the answering side)


def _rates(tau: float, answerable: list[float], unanswerable: list[float]) -> tuple[float, float]:
    refusal = sum(s < tau for s in unanswerable) / len(unanswerable)
    false_refusal = sum(s < tau for s in answerable) / len(answerable)
    return refusal, false_refusal


def choose_threshold(answerable: list[float], unanswerable: list[float],
                     max_false_refusal: float = MAX_FALSE_REFUSAL) -> ThresholdChoice:
    """Best τ by the §8.5 rule, from the top reranker score of each question."""
    if not answerable or not unanswerable:
        raise ValueError("need at least one answerable and one unanswerable question")
    pts = sorted({*answerable, *unanswerable})
    candidates = [pts[0] - 1.0, *((a + b) / 2 for a, b in zip(pts, pts[1:], strict=False)),
                  pts[-1] + 1.0]
    scored = [(tau, *_rates(tau, answerable, unanswerable)) for tau in candidates]
    feasible = [row for row in scored if row[2] <= max_false_refusal]  # τ = min−1 always is
    best = max(row[1] for row in feasible)
    tied = [row[0] for row in feasible if row[1] == best]
    tau = (min(tied) + max(tied)) / 2  # the middle of the plateau
    refusal, false_refusal = _rates(tau, answerable, unanswerable)
    refused = [s for s in unanswerable if s < tau]
    return ThresholdChoice(
        tau=round(tau, 2), refusal_accuracy=refusal, false_refusal_rate=false_refusal,
        margin_below=round(tau - max(refused), 2) if refused else float("nan"),
        margin_above=round(min(answerable) - tau, 2))


def main() -> int:
    settings = get_settings()
    dev = [g for g in load_golden(GOLDEN) if g.split == "dev"]
    pipeline = RagPipeline(settings)
    pipeline.rank("warm-up question")  # load the models before scoring
    rows = []  # (top score, golden item)
    for g in dev:
        ranked = pipeline.rank(g.question)
        rows.append((ranked[0].score, g, ranked[0].chunk_id))
        print(f"  {g.id} {'answerable  ' if g.answerable else 'UNANSWERABLE'} "
              f"top score {ranked[0].score:7.2f}  {g.question[:60]}")
    answerable = [s for s, g, _ in rows if g.answerable]
    unanswerable = [s for s, g, _ in rows if not g.answerable]
    choice = choose_threshold(answerable, unanswerable)
    print(f"\nτ = {choice.tau}  refusal accuracy {choice.refusal_accuracy:.2f}  "
          f"false refusal {choice.false_refusal_rate:.2f}")

    n_un, n_an = len(unanswerable), len(answerable)
    lines = [
        "# Relevance threshold τ (D-15)", "",
        f"Generated by `python -m scripts.tune_threshold` on {dt.date.today().isoformat()}, "
        f"git commit `{git_commit()}`.",
        f"Reranker `{settings.reranker_model}` on top of hybrid `{settings.embedding_model}`; "
        "**dev split only** (the test split is not used for tuning, §11.1).", "",
        "Rule (§8.5): the τ with the highest refusal accuracy on unanswerable questions while "
        "rejecting at most 1 in 20 answerable ones; if several τ tie, the middle of that range.",
        "", f"## Chosen: τ = {choice.tau}", "",
        f"Set `RELEVANCE_THRESHOLD={choice.tau}` in `.env` / `.env.example`. A question is "
        "refused (\"not covered\", no LLM call) when its best reranker score is **below** τ.", "",
        "| | Result on dev | Questions |", "|---|---|---|",
        f"| Refusal accuracy | {choice.refusal_accuracy:.2f} | "
        f"{round(choice.refusal_accuracy * n_un)} of {n_un} unanswerable refused |",
        f"| False refusal rate | {choice.false_refusal_rate:.2f} | "
        f"{round(choice.false_refusal_rate * n_an)} of {n_an} answerable refused |",
        f"| Margin to the refused questions | {choice.margin_below} | score units |",
        f"| Margin to the weakest answerable | {choice.margin_above} | score units |", "",
        "## Top reranker score of every dev question", "",
        "| Question | Type | Top score | Decision at τ |", "|---|---|---|---|"]
    for score, g, _ in sorted(rows, key=lambda r: r[0]):
        decision = "refused" if score < choice.tau else "answered"
        kind = "answerable" if g.answerable else "**unanswerable**"
        lines.append(f"| {g.id} {g.question} | {kind} | {score:.2f} | {decision} |")
    lines += [
        "", "## Limits of this estimate", "",
        f"- Only **{n_un} unanswerable** dev questions exist, so refusal accuracy here is "
        f"{round(choice.refusal_accuracy * n_un)}/{n_un}; it says little about unseen unanswerable "
        "questions. The release gate measures the 5 test questions (target ≥ 4 of 5, §11.4).",
        f"- With {n_an} answerable questions, one refusal is {100 / n_an:.1f} points of false "
        "refusal rate.",
        "- Questions the reranker scores above τ but the documents do not answer are still "
        "caught by the model's own `NOT_COVERED` reply (answer_type `model_refusal`).", ""]
    out = settings.reports_dir / "threshold.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
