"""Write docs/golden_review.md: every golden question with the source text it expects.

Usage (from backend/):  python -m scripts.golden_review

START_HERE M2 is done when each expected section has been checked by opening the document.
This sheet puts the page number and the start of each expected section next to the question,
with a checkbox to tick once you have confirmed it in the PDF / SOP itself.
"""

import textwrap

from config import PROJECT_ROOT, get_settings
from src.evaluation.golden import load_golden
from src.ingestion.manifest import load_manifest
from src.ingestion.md_loader import load_markdown
from src.ingestion.pdf_loader import load_pdf
from src.ingestion.sections import detect_sections

EXCERPT_CHARS = 420


def section_index(settings) -> dict[str, dict[str, tuple[int | None, str]]]:
    """doc_code → section label → (first page, text of the section and its subsections)."""
    index: dict[str, dict[str, tuple[int | None, str]]] = {}
    for e in load_manifest(settings.manifest_path):
        path = settings.corpus_dir / e.file
        md = path.suffix == ".md"
        sections = detect_sections(load_markdown(path) if md else load_pdf(path), md)
        texts: dict[str, list[str]] = {}
        pages: dict[str, int | None] = {}
        for s in sections:
            chain, parent = [s.label], s.parent
            while parent:
                chain.append(parent)
                parent = next((x.parent for x in sections if x.label == parent), None)
            for label in chain:  # a section's text includes its subsections
                texts.setdefault(label, []).extend(x.text for x in s.lines)
                pages.setdefault(label, s.lines[0].page)
        index[e.doc_code] = {k: (pages[k], " ".join(v)) for k, v in texts.items()}
    return index


def main() -> None:
    settings = get_settings()
    golden = load_golden(PROJECT_ROOT / "backend/tests/golden/golden_set.jsonl")
    index = section_index(settings)
    out = [
        "# Golden set review",
        "",
        "Generated by `python -m scripts.golden_review`. For each question, open the document at",
        "the page shown and confirm the expected section really answers it, then tick the box.",
        "Excerpts show the start of the section only. Fix errors in `golden_set.jsonl`, not here.",
        "Page numbers are PDF page numbers (as your PDF viewer shows them), not printed ones.",
        "",
    ]
    for g in golden:
        tag = f"{g.split} · {g.category}"
        out += [f"## {g.id} ({tag})", "", f"**Q:** {g.question}", ""]
        if not g.answerable:
            out += ["- [ ] Confirmed that no document answers this (should be refused)", ""]
            continue
        out += ["**Key facts:** " + "; ".join(g.key_facts), ""]
        for e in g.expected:
            page, text = index[e.doc_code][e.section]
            where = f"page {page}" if page else "SOP (no pages)"
            excerpt = textwrap.shorten(text, EXCERPT_CHARS, placeholder=" …")
            out += [f"- [ ] **{e.doc_code} §{e.section}** ({where})", f"  > {excerpt}", ""]
    path = PROJECT_ROOT / "docs/golden_review.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {path} ({len(golden)} questions)")


if __name__ == "__main__":
    main()
